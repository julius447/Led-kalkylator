/* =============================================================================
   build-snippets.js — deterministic repackaging of the LED calculator
   -----------------------------------------------------------------------------
   Reads the 5 source files (../styles.css ../data.js ../engine.js ../app.js
   ../index.html) and writes the 3 Fluent-Snippets-ready deliverables:

     1-ampy-led-styles.css    ← styles.css VERBATIM + the 62.5% base
     2-ampy-led-scripts.js    ← data.js + engine.js + app.js VERBATIM, in order
     3-ampy-led-shortcode.php ← shortcode that prints the EXACT markup + REST endpoint

   The point: CSS/JS are built by PURE CONCATENATION of the unchanged sources (no
   hand-editing → no drift). The PHP injects the EXACT markup from index.html.
   Run: node build-snippets.js   (from this folder). Idempotent.
   ============================================================================= */
"use strict";
var fs = require("fs");
var path = require("path");

var SRC = path.join(__dirname, "..");
var OUT = __dirname;
function read(f) { return fs.readFileSync(path.join(SRC, f), "utf8"); }
function write(f, s) { fs.writeFileSync(path.join(OUT, f), s); console.log("  ✓ " + f + " (" + s.length + " chars)"); }

var stylesCss = read("styles.css");
var dataJs = read("data.js");
var engineJs = read("engine.js");
var appJs = read("app.js");
var indexHtml = read("index.html");

/* --- 1. CSS ---------------------------------------------------------------- */
// Fluent Snippets "CSS" snippet. IMPORTANT about ordering: styles.css begins
// (after comments) with an @import for the web fonts. Per the CSS spec, @import
// must come BEFORE any style rule — otherwise it is ignored and the fonts never
// load. So our header stays a pure comment (comments before @import are fine) and
// the base html{font-size:62.5%} is appended LAST, after all of styles.css. The
// source stays VERBATIM.
var cssHeader =
"/* ==========================================================================\n" +
"   AMPY LED CALCULATOR — SNIPPET 1 of 3: CSS\n" +
"   Paste as a Fluent Snippets snippet of type 'CSS'.\n" +
"   All COMPONENT styling is scoped under .ampy-calc. The file additionally sets\n" +
"   two global lines: the @import for the fonts (below) and the 62.5% base (last).\n" +
"   Generated by build-snippets.js — DO NOT EDIT here; change ../styles.css.\n" +
"   ========================================================================== */\n\n";
// The base is appended LAST so the @import stays the first rule (otherwise no fonts load).
var cssBase =
"\n\n/* --- Design-system base: 1rem = 10px ---------------------------------------\n" +
"   Same base as Ampy's battery/EV calculator. ampy.se already runs this globally\n" +
"   (no-op there). Placed LAST on purpose: a style rule before the @import above\n" +
"   would invalidate the font import. If you scope this snippet to only the\n" +
"   calculator pages, this line affects nothing else on the site. */\n" +
"html { font-size: 62.5%; }\n";
write("1-ampy-led-styles.css", cssHeader + stylesCss + cssBase);

/* --- 2. JS ----------------------------------------------------------------- */
// Fluent Snippets "JS" snippet (footer). Order: data → engine → app.
// data.js sets window.AMPY_LED_DATA, engine.js sets window.AmpyLED,
// app.js (IIFE) self-initialises on DOM-ready. Each part is VERBATIM.
function banner(t) {
  return "\n\n/* ==========================================================================\n" +
         "   " + t + "\n" +
         "   ========================================================================== */\n";
}
var jsHeader =
"/* ==========================================================================\n" +
"   AMPY LED CALCULATOR — SNIPPET 2 of 3: JAVASCRIPT\n" +
"   Paste as a Fluent Snippets snippet of type 'JS' (loads in the footer).\n" +
"   Contains data.js + engine.js + app.js concatenated in EXACTLY this order.\n" +
"   Generated by build-snippets.js — DO NOT EDIT here; change the source files.\n" +
"\n" +
"   The ONLY thing you might change for production: search for 'endpoint: null'\n" +
"   below and set it to your REST URL (see snippet 3) if you want to capture leads\n" +
"   server-side instead of mailto. Leaving null = mail-client fallback (no lead lost).\n" +
"   ========================================================================== */\n";
write("2-ampy-led-scripts.js", jsHeader + banner("PART 1/3 — DATA LAYER (data.js)") + dataJs +
      banner("PART 2/3 — ENGINE (engine.js)") + engineJs +
      banner("PART 3/3 — RENDERER (app.js)") + appJs + "\n");

/* --- 3. PHP + HTML --------------------------------------------------------- */
// Extract the .ampy-calc block VERBATIM from index.html (opening div → outer
// </div> just before <script>). Only the data-sida value is swapped for a
// placeholder that PHP replaces with the escaped shortcode attribute. No other
// markup is touched.
var startTag = '<div class="ampy-calc" id="ampyLed"';
var s = indexHtml.indexOf(startTag);
var e = indexHtml.indexOf('<script src="data.js">');
if (s < 0 || e < 0) { throw new Error("Could not find the markup boundaries in index.html"); }
var block = indexHtml.slice(s, e).replace(/\s+$/, ""); // up to and incl. outer </div>, no trailing whitespace
if (block.indexOf('data-sida="belysning"') < 0) { throw new Error("data-sida attribute missing from the markup"); }
block = block.replace('data-sida="belysning"', 'data-sida="__AMPY_SIDA__"');
if (/^\s*HTML;\s*$/m.test(block)) { throw new Error("Markup contains the nowdoc terminator HTML; — change the token"); }

var php =
"<?php\n" +
"/**\n" +
" * ==========================================================================\n" +
" *  AMPY LED CALCULATOR — SNIPPET 3 of 3: PHP + HTML (shortcode + lead endpoint)\n" +
" *  Paste as a Fluent Snippets snippet of type 'PHP'. Leave it running everywhere\n" +
" *  (do NOT page-condition it). It outputs NO CSS/JS — snippets 1 and 2 do that.\n" +
" *  It gives you:\n" +
" *    - a shortcode  [ampy_led_kalkylator]  that prints the EXACT same markup as\n" +
" *      the prototype (drop it in a Bricks 'Shortcode' element).\n" +
" *      Change the per-page preset:  [ampy_led_kalkylator sida=\"spotlight\"]\n" +
" *      Valid 'sida' values: belysning · inomhusbelysning · utomhusbelysning ·\n" +
" *      spotlight · armaturer  (see embed_preset in snippet 2).\n" +
" *    - a REST endpoint  POST /wp-json/ampy/v1/led-offert  for lead capture\n" +
" *      (optional — see snippet 2, 'endpoint'). Honeypot + rate limit + validation.\n" +
" *  Generated by build-snippets.js — the markup is index.html VERBATIM.\n" +
" *  NOTE: the shortcode tag and the lead-email text are intentionally Swedish\n" +
" *  (the tool is a Swedish product; Ampy staff read the lead emails in Swedish).\n" +
" * ========================================================================== */\n" +
"\n" +
"if ( ! defined( 'ABSPATH' ) ) { exit; }\n" +
"\n" +
"/* --- Shortcode: [ampy_led_kalkylator sida=\"belysning\"] --------------------- */\n" +
"add_shortcode( 'ampy_led_kalkylator', function ( $atts ) {\n" +
"\t$a = shortcode_atts( array( 'sida' => 'belysning' ), $atts, 'ampy_led_kalkylator' );\n" +
"\t$markup = <<<'HTML'\n" +
block + "\n" +
"HTML;\n" +
"\treturn str_replace( '__AMPY_SIDA__', esc_attr( $a['sida'] ), $markup );\n" +
"} );\n" +
"\n" +
"/* --- Lead endpoint (optional): POST /wp-json/ampy/v1/led-offert ------------\n" +
"   Same-origin. Set data.lead.endpoint = \"/wp-json/ampy/v1/led-offert\" in\n" +
"   snippet 2 to activate. If you leave endpoint = null the mailto fallback is\n" +
"   used and this route is never touched. */\n" +
"add_action( 'rest_api_init', function () {\n" +
"\tregister_rest_route( 'ampy/v1', '/led-offert', array(\n" +
"\t\t'methods'             => 'POST',\n" +
"\t\t'permission_callback' => '__return_true', // public form; guarded inside the callback\n" +
"\t\t'callback'            => function ( WP_REST_Request $req ) {\n" +
"\t\t\t$d = $req->get_json_params();\n" +
"\n" +
"\t\t\t// 1) Honeypot: a filled company_url is a bot. Pretend success, send nothing.\n" +
"\t\t\tif ( ! empty( $d['company_url'] ) ) { return new WP_REST_Response( array( 'ok' => true ), 200 ); }\n" +
"\n" +
"\t\t\t// 2) Per-IP rate limit: max 5 submits / 10 min.\n" +
"\t\t\t$ip  = isset( $_SERVER['REMOTE_ADDR'] ) ? $_SERVER['REMOTE_ADDR'] : '';\n" +
"\t\t\t$key = 'ampy_led_' . md5( $ip );\n" +
"\t\t\t$n   = (int) get_transient( $key );\n" +
"\t\t\tif ( $n >= 5 ) { return new WP_REST_Response( array( 'ok' => false ), 429 ); }\n" +
"\t\t\tset_transient( $key, $n + 1, 10 * MINUTE_IN_SECONDS );\n" +
"\n" +
"\t\t\t// 3) Require ALL fields the client requires (client validation is bypassable).\n" +
"\t\t\tif ( empty( $d['namn'] ) || empty( $d['epost'] ) || empty( $d['telefon'] )\n" +
"\t\t\t\t|| empty( $d['postnummer'] ) || empty( $d['samtycke'] ) ) {\n" +
"\t\t\t\treturn new WP_REST_Response( array( 'ok' => false ), 400 );\n" +
"\t\t\t}\n" +
"\t\t\t$namn  = sanitize_text_field( $d['namn'] );\n" +
"\t\t\t$epost = sanitize_email( $d['epost'] );\n" +
"\t\t\tif ( ! is_email( $epost ) ) { return new WP_REST_Response( array( 'ok' => false ), 400 ); }\n" +
"\n" +
"\t\t\t$g = function ( $k ) use ( $d ) { return isset( $d[ $k ] ) ? sanitize_text_field( $d[ $k ] ) : ''; };\n" +
"\t\t\t// Lead email body — Swedish on purpose (Ampy staff read it).\n" +
"\t\t\t$body = \"Ny LED-offertförfrågan\\n\\n\"\n" +
"\t\t\t\t. \"Namn: $namn\\nE-post: $epost\\n\"\n" +
"\t\t\t\t. 'Telefon: '  . $g( 'telefon' )    . \"\\n\"\n" +
"\t\t\t\t. 'Postnr: '   . $g( 'postnummer' ) . \"\\n\\n\"\n" +
"\t\t\t\t. 'Segment: '  . $g( 'segment' )    . \"\\n\"\n" +
"\t\t\t\t. 'Antal: '    . intval( isset( $d['antal'] ) ? $d['antal'] : 0 ) . ' × ' . $g( 'typ_id' ) . \"\\n\"\n" +
"\t\t\t\t. 'Brinntid: ' . floatval( isset( $d['timmar_dag'] ) ? $d['timmar_dag'] : 0 ) . ' h/dygn, område ' . $g( 'elprisomrade' ) . \"\\n\"\n" +
"\t\t\t\t. 'Årlig besparing: '    . intval( isset( $d['arlig_besparing'] ) ? $d['arlig_besparing'] : 0 )     . \" kr/år\\n\"\n" +
"\t\t\t\t. 'Uppskattad kostnad: ' . intval( isset( $d['uppskattad_kostnad'] ) ? $d['uppskattad_kostnad'] : 0 ) . \" kr\\n\"\n" +
"\t\t\t\t. 'Samtycke: '  . $g( 'samtycke_tid' );\n" +
"\n" +
"\t\t\t// 4) Header-injection guard: strip CR/LF from anything placed in a mail header.\n" +
"\t\t\t$reply = str_replace( array( \"\\r\", \"\\n\" ), '', $epost );\n" +
"\t\t\twp_mail( 'offert@ampy.se', 'LED-offert – ' . $namn, $body, array( 'Reply-To: ' . $reply ) );\n" +
"\t\t\t// TODO: push to your CRM here if you like. NEVER put raw $d[...] in mail headers.\n" +
"\t\t\treturn new WP_REST_Response( array( 'ok' => true ), 200 );\n" +
"\t\t},\n" +
"\t) );\n" +
"} );\n";
write("3-ampy-led-shortcode.php", php);

/* --- WP-faithful preview (for OUR verification only, not a deliverable) ------
   Simulates EXACTLY how WordPress + Fluent Snippets loads the pieces:
     - snippet 1 (CSS, with the 62.5% base) in <head>
     - the shortcode markup (data-sida=belysning) in <body>
     - snippet 2 (JS) just before </body>
   The page chrome (body margin/bg) matches the prototype's index.html so any
   pixel diff can only come from the repackaging, not from the page frame. */
var previewMarkup = block.replace('data-sida="__AMPY_SIDA__"', 'data-sida="belysning"');
var preview =
"<!DOCTYPE html>\n<html lang=\"sv\">\n<head>\n" +
"  <meta charset=\"UTF-8\" />\n" +
"  <meta name=\"viewport\" content=\"width=device-width, initial-scale=1.0\" />\n" +
"  <title>WP preview — LED calculator (Fluent Snippets)</title>\n" +
"  <!-- Preview chrome (NOT part of the deliverable; on real WP this is the page/theme's job) -->\n" +
"  <style>body{margin:0;background:rgb(247,249,251)}</style>\n" +
"  <!-- SNIPPET 1 (CSS) — loaded as a Fluent CSS snippet in <head>. Contains the 62.5% base. -->\n" +
"  <link rel=\"stylesheet\" href=\"../1-ampy-led-styles.css\" />\n" +
"</head>\n<body>\n\n" +
"  <!-- SNIPPET 3 (shortcode output) — the exact markup [ampy_led_kalkylator] returns -->\n" +
previewMarkup + "\n\n" +
"  <!-- SNIPPET 2 (JS) — loaded as a Fluent JS snippet in the footer -->\n" +
"  <script src=\"../2-ampy-led-scripts.js\"></script>\n" +
"</body>\n</html>\n";
write("_preview/index.html", preview);

console.log("\nDone. 3 snippets + WP preview generated in " + OUT);
